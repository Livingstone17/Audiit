import writeXlsxFile from 'write-excel-file/browser'
import { COMPANY, PROCUREMENT_POLICY } from '../data/company'
import { getDataset } from './registry'

/** Generate and download a dataset as a real .xlsx workbook. */
export async function downloadDataset(id: string): Promise<void> {
  const dataset = getDataset(id)
  const sheet = dataset.sheets[0]!
  const header = sheet.columns.map((c) => c.label)
  const body = sheet.rows.map((row) => sheet.columns.map((c) => row[c.key]))
  const file = await writeXlsxFile(
    [header, ...body],
    {
      sheet: sheet.name,
      stickyRowsCount: 1,
      columns: sheet.columns.map((c) => ({ width: c.width ?? 16 })),
    },
  )
  await file.toFile(dataset.filename)
}

/** Render the procurement policy as a formatted multi-page PDF (lazy-loaded). */
export async function downloadPolicyDoc(): Promise<void> {
  const { jsPDF } = await import('jspdf')
  const doc = new jsPDF({ unit: 'mm', format: 'a4' })
  const pageWidth = doc.internal.pageSize.getWidth()
  const pageHeight = doc.internal.pageSize.getHeight()
  const margin = 18
  const maxWidth = pageWidth - margin * 2
  let y = margin

  const ensureSpace = (needed: number) => {
    if (y + needed > pageHeight - margin) {
      doc.addPage()
      y = margin
    }
  }

  // Title block
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(18)
  doc.text(COMPANY.name, margin, y)
  y += 8
  doc.setFontSize(12)
  doc.text('Procurement Policy — September 2025', margin, y)
  y += 6
  doc.setDrawColor(16, 185, 129)
  doc.setLineWidth(0.8)
  doc.line(margin, y, margin + 40, y)
  y += 8

  doc.setFont('helvetica', 'normal')
  doc.setFontSize(10)

  for (const section of PROCUREMENT_POLICY) {
    ensureSpace(16)
    doc.setFont('helvetica', 'bold')
    doc.setFontSize(12)
    doc.text(section.heading, margin, y)
    y += 6
    doc.setFont('helvetica', 'normal')
    doc.setFontSize(10)
    for (const para of section.paragraphs) {
      const lines = doc.splitTextToSize(para, maxWidth) as string[]
      for (const line of lines) {
        ensureSpace(6)
        doc.text(line, margin, y)
        y += 5
      }
      y += 2
    }
    y += 3
  }

  ensureSpace(12)
  doc.setFont('helvetica', 'italic')
  doc.setFontSize(8)
  doc.text(
    'Apex Manufacturing Group — Internal document. Fictional document generated by AuditLab for training purposes.',
    margin,
    pageHeight - 12,
  )

  doc.save('procurement_policy.pdf')
}

export interface DownloadableDoc {
  id: string
  label: string
  filename: string
  kind: 'pdf'
  description: string
  download: () => void | Promise<void>
}

export const SUPPORTING_DOCS: Record<string, DownloadableDoc> = {
  'procurement-policy': {
    id: 'procurement-policy',
    label: 'Procurement Policy',
    filename: 'procurement_policy.pdf',
    kind: 'pdf',
    description: 'Company policy: approvals, three-way match, vendor rules and documentation retention.',
    download: downloadPolicyDoc,
  },
}
